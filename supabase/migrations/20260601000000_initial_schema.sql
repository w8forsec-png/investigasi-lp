create policy teams_read_scoped on public.teams for select to authenticated
using (
  (public.current_cms_role() = 'admin' or id = public.current_cms_team_id())
  and (deleted_at is null or public.current_cms_role() = 'admin')
);

create policy users_read_scoped on public.users for select to authenticated
using (
  public.current_cms_role() = 'admin'
  or (
    team_id = public.current_cms_team_id()
    and role <> 'admin'
    and (deleted_at is null or public.current_cms_role() = 'admin')
  )
);

create policy cases_read_scoped on public.cases for select to authenticated
using (
  deleted_at is null
  and (
    public.current_cms_role() = 'admin'
    or (
      team_id = public.current_cms_team_id()
      and (
        public.current_cms_role() in ('leader', 'analyst')
        or exists (
          select 1 from public.case_members m
          where m.case_id = id and m.user_id = public.current_cms_user_id()
        )
      )
    )
  )
);

create policy case_members_read_scoped on public.case_members for select to authenticated
using (public.can_access_case(case_id));

create policy profiles_read_scoped on public.profiles for select to authenticated
using (deleted_at is null and public.can_access_case(case_id));

create policy field_reports_read_scoped on public.field_reports for select to authenticated
using (deleted_at is null and public.can_access_case(case_id));

create policy technical_entries_read_scoped on public.technical_entries for select to authenticated
using (deleted_at is null and public.can_access_case(case_id));

create policy audit_read_admin on public.audit_log for select to authenticated
using (public.current_cms_role() = 'admin');

grant select on public.teams, public.users, public.cases, public.case_members,
  public.profiles, public.field_reports, public.technical_entries, public.audit_log
to authenticated;
grant execute on function public.current_cms_user_id(), public.current_cms_role(),
  public.current_cms_team_id(), public.can_access_case(bigint) to authenticated;
revoke all on function public.create_case_with_victim(text, text, date, text, text, bigint, bigint, text, text, text, text) from public, anon, authenticated;
revoke all on function public.archive_team(bigint, bigint) from public, anon, authenticated;
grant execute on function public.create_case_with_victim(text, text, date, text, text, bigint, bigint, text, text, text, text),
  public.archive_team(bigint, bigint) to service_role;

