create function public.current_cms_user_id()
returns bigint
language sql
stable
security definer
set search_path = ''
as $$
  select u.id from public.users u
  where u.auth_user_id = (select auth.uid())
    and u.active = true and u.deleted_at is null
  limit 1
$$;

create function public.current_cms_role()
returns text
language sql
stable
security definer
set search_path = ''
as $$
  select case when u.is_analyst then 'analyst' else u.role end
  from public.users u
  where u.auth_user_id = (select auth.uid())
    and u.active = true and u.deleted_at is null
  limit 1
$$;

create function public.current_cms_team_id()
returns bigint
language sql
stable
security definer
set search_path = ''
as $$
  select u.team_id from public.users u
  where u.auth_user_id = (select auth.uid())
    and u.active = true and u.deleted_at is null
  limit 1
$$;

create function public.can_access_case(target_case_id bigint)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.cases c
    where c.id = target_case_id
      and (
        public.current_cms_role() = 'admin'
        or (
          c.team_id = public.current_cms_team_id()
          and (
            public.current_cms_role() in ('leader', 'analyst')
            or exists (
              select 1 from public.case_members m
              where m.case_id = c.id and m.user_id = public.current_cms_user_id()
            )
          )
        )
      )
  )
$$;

create function public.create_case_with_victim(
  p_lp_number text,
  p_title text,
  p_reported_at date,
  p_statute text,
  p_location text,
  p_team_id bigint,
  p_actor_id bigint,
  p_victim_name text,
  p_victim_nik text,
  p_victim_address text,
  p_victim_phone text
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  created_case_id bigint;
begin
  insert into public.cases (lp_number, title, reported_at, statute, location, status, team_id, created_by)
  values (p_lp_number, p_title, p_reported_at, p_statute, p_location, 'Aktif', p_team_id, p_actor_id)
  returning id into created_case_id;

  if coalesce(p_victim_name, '') <> '' then
    insert into public.profiles (case_id, profile_type, name, nik, address, phone, created_by)
    values (created_case_id, 'Korban', p_victim_name, coalesce(p_victim_nik, ''),
      coalesce(p_victim_address, ''), coalesce(p_victim_phone, ''), p_actor_id);
  end if;

  insert into public.audit_log (actor_id, action, case_id, detail)
  values (p_actor_id, 'case.created', created_case_id, p_lp_number);
  return created_case_id;
end
$$;

create function public.archive_team(target_team_id bigint, actor_id bigint)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  archived_at timestamptz := now();
begin
  if not exists (select 1 from public.teams where id = target_team_id) then
    raise exception 'Tim tidak ditemukan.' using errcode = 'P0002';
  end if;
  if exists (select 1 from public.cases where team_id = target_team_id and deleted_at is null) then
    raise exception 'Arsipkan seluruh perkara tim terlebih dahulu.' using errcode = '23514';
  end if;

  update public.users set active = false, deleted_at = archived_at
  where team_id = target_team_id and deleted_at is null;
  update public.teams set deleted_at = archived_at where id = target_team_id;
  insert into public.audit_log (actor_id, action, detail)
  values (actor_id, 'team.archived', 'team:' || target_team_id::text);
end
$$;

