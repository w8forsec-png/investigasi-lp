create table public.teams (
  id bigint generated by default as identity primary key,
  name text not null unique,
  description text not null default '',
  deleted_at timestamptz,
  created_at timestamptz not null default now()
);

create table public.users (
  id bigint generated by default as identity primary key,
  auth_user_id uuid unique references auth.users(id) on delete set null,
  name text not null,
  rank_number text not null default '',
  specialty text not null default '',
  role text not null check (role in ('admin', 'leader', 'member')),
  is_analyst boolean not null default false,
  team_id bigint references public.teams(id),
  username text not null unique,
  active boolean not null default true,
  deleted_at timestamptz,
  created_at timestamptz not null default now(),
  constraint admin_without_team check (role <> 'admin' or team_id is null)
);

create table public.cases (
  id bigint generated by default as identity primary key,
  lp_number text not null unique,
  title text not null,
  reported_at date not null,
  statute text not null default '',
  location text not null default '',
  status text not null default 'Aktif' check (status in ('Aktif', 'Proses', 'Selesai')),
  team_id bigint not null references public.teams(id),
  created_by bigint not null references public.users(id),
  created_at timestamptz not null default now(),
  deleted_at timestamptz
);

create table public.case_members (
  case_id bigint not null references public.cases(id) on delete cascade,
  user_id bigint not null references public.users(id),
  duty text not null default '',
  primary key (case_id, user_id)
);

create table public.profiles (
  id bigint generated by default as identity primary key,
  case_id bigint not null references public.cases(id) on delete cascade,
  profile_type text not null default 'Terduga' check (profile_type in ('Korban', 'Terduga')),
  name text not null,
  alias text not null default '',
  nik text not null default '',
  address text not null default '',
  phone text not null default '',
  role_in_case text not null default '',
  notes text not null default '',
  created_by bigint not null references public.users(id),
  created_at timestamptz not null default now(),
  deleted_at timestamptz
);

create table public.field_reports (
  id bigint generated by default as identity primary key,
  case_id bigint not null references public.cases(id) on delete cascade,
  source_unit text not null,
  title text not null,
  reference text not null default '',
  details text not null,
  created_by bigint not null references public.users(id),
  created_at timestamptz not null default now(),
  deleted_at timestamptz
);

create table public.technical_entries (
  id bigint generated by default as identity primary key,
  case_id bigint not null references public.cases(id) on delete cascade,
  category text not null,
  title text not null,
  target_ref text not null default '',
  findings text not null,
  field_report_id bigint references public.field_reports(id),
  parent_entry_id bigint references public.technical_entries(id),
  progress_status text not null default 'Analisis awal' check (progress_status in ('Analisis awal', 'Tindak lanjut', 'Selesai')),
  created_by bigint not null references public.users(id),
  created_at timestamptz not null default now(),
  deleted_at timestamptz
);

create table public.audit_log (
  id bigint generated by default as identity primary key,
  actor_id bigint not null references public.users(id),
  action text not null,
  case_id bigint references public.cases(id),
  detail text not null default '',
  created_at timestamptz not null default now()
);

create index cases_team_created_idx on public.cases(team_id, created_at desc);
